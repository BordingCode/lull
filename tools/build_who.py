#!/usr/bin/env python3
"""Build js/who.js from the WHO growth-standard LMS tables in docs/who/.

The CSVs are the WHO Child Growth Standards (2006), birth-24 months, as
republished by CDC: https://www.cdc.gov/growthcharts/who-data-files.htm
Run: python3 tools/build_who.py
"""
import csv, json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
names = {'weight': 'Weight-for-age', 'length': 'Length-for-age', 'head': 'Head-Circumference-for-age'}
out = {}
for key, part in names.items():
    for sex, word in (('girl', 'Girls'), ('boy', 'Boys')):
        rows = list(csv.DictReader(open(root / f'docs/who/WHO-{word}-{part}-Percentiles.csv', encoding='utf-8-sig')))
        assert [int(r['Month']) for r in rows] == list(range(25)), (key, sex)
        out.setdefault(key, {})[sex] = [[float(r['L']), float(r['M']), float(r['S'])] for r in rows]

js = ('// ===== Lull - WHO Child Growth Standards (2006), birth to 24 months =====\n'
      '// GENERATED by tools/build_who.py from docs/who/*.csv - do not edit by hand.\n'
      '// [L, M, S] per completed month 0..24, for weight (kg), length (cm), head (cm).\n'
      f'export const WHO = {json.dumps(out, separators=(",", ":"))};\n')
(root / 'js/who.js').write_text(js)
print('wrote js/who.js', len(js), 'bytes')
